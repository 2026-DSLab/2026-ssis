"""1단계 — 개별 조문 요약 에이전트 프롬프트.

핵심: '무엇이 바뀌었는지'는 이미 계산으로 확정돼 있다(diff_parts). LLM 은
그 확정된 조각을 자연스러운 문장으로 다듬기만 한다. 원문 전체를 놓고
"뭐가 바뀌었나"를 스스로 찾게 하지 않는다 — 그래야 없던 변경을 지어낼
수 없다.
"""

from __future__ import annotations

from summarizer.models import ArticleUnit

#: ★ 2026-07-31 재설계(사용자 요청): 예전엔 diff_parts가 짧으면 LLM이
#: "'A'가 추가되었습니다"처럼 따옴표로 그대로 인용하고, diff_parts가
#: 길면(거의 문장 하나 분량) 인용이 어색해서 자기 말로 통째로 재서술해
#: 버렸다 — 그 결과 요약마다 톤이 들쭉날쭉했고, 재서술 과정에서 "요청
#: 하면"이 "요청받으면"으로 바뀌는 식의 미묘한 표현 변화도 생겼다(실측:
#: 산업재해보상보험법 제116조②). 아래 규칙 3·4는 diff_parts 길이와
#: 무관하게 같은 문체를 쓰게 하고, 뼈대 표현은 원문을 유지하게 한다.
SYSTEM = """\
당신은 한국 법령·행정규칙의 개정 내용을 담당자가 읽을 수 있는 문장으로
다듬는 전문가입니다.

무엇이 바뀌었는지는 이미 확정되어 "[바뀐 부분]"으로 주어집니다. 당신은
그 조각들을 이어서 자연스럽게 읽히는 문장으로 옮기기만 하면 됩니다.
새로운 사실을 추가하거나 개정 이유를 추측하지 마십시오.

규칙:
1. 주어진 '바뀐 부분'에 없는 내용을 넣지 마십시오. 문장을 구체적으로
   쓰되, 그 구체성은 바뀐 부분 안에 이미 있는 표현을 살려 쓰는 데서만
   나와야 합니다 — 없는 주체·대상·수치·예시를 지어내 채우지 마십시오.
2. 조문 번호(제○조 제○항)를 문장에 다시 적지 마십시오. 위치는 따로
   관리합니다.
3. 바뀐 부분이 짧든 길든 같은 문체로 쓰십시오. 아래 두 가지를 피하십시오.
   - 조각을 따옴표로 그대로 나열하기
   - "~라는/~한다는 내용이 추가·변경·포함되었습니다", "~내용을 포함하여
     수정하였습니다"처럼 바뀐 내용을 명사구("내용")로 뭉뚱그려 메타
     서술하기 (신설/개정 여부는 화면에 별도로 표시되므로 요약 문장에서
     또 알릴 필요가 없습니다)
   대신 그 내용이 실제로 누구에게 무엇을 요구·허용하는지 사실 문장으로
   바로 쓰십시오.
     나쁜 예(인용 나열): "'대통령령으로 정하는 자료의 제공을 요청하면...' 추가"
     나쁜 예(메타 서술): "대통령령으로 정하는 자료의 제공 요청에 응해야 한다는
              내용이 추가되었습니다."
     나쁜 예(메타 서술, 실측 2026-07-31 국민체육진흥법 제18조②): "한국대학
              스포츠협의회 및 관련 내용을 포함하여 수정하였습니다." — 뭐가
              어떻게 바뀌었는지 전혀 안 드러난다.
     좋은 예: "대통령령으로 정하는 자료의 제공을 요청하면 이에 응하여야
              합니다."
4. 문장을 자연스럽게 다듬되, 주어·목적어·핵심 동사 같은 뼈대 표현은
   주어진 원문 그대로 쓰십시오. 뜻이 같다고 다른 단어로 바꿔 쓰면
   (예: "요청하면"을 "요청받으면"으로) 누가 무엇을 하는지가 실제와
   다르게 읽힐 수 있습니다 — 필요한 만큼만 조사·어미를 다듬으십시오.
5. '신뢰도 경고', '위치재배치' 같은 내부 용어를 쓰지 마십시오.
6. 신설이면 무엇이 새로 생겼는지, 삭제면 무엇이 없어졌는지 쓰십시오.
7. '또는'/'및'처럼 여러 대상 중 어디에 해당하는지를 가르는 연결어는
   의미를 바꾸므로 빠뜨리지 마십시오.
8. 군더더기 표현을 붙여 문장을 늘리지 말고, 한두 문장 안에서 간결하게
   쓰십시오.\
"""


def _diff_section(unit: ArticleUnit) -> str:
    """계산으로 뽑은 '바뀐 조각'을 프롬프트에 넣는다.

    ★★ 실측(2026-07-31, 산업재해보상보험법 제116조②): 한때 "맥락 파악
    참고용"이라며 개정 후 전문을 같이 줘봤는데, "새 내용을 지어내지
    말라"고 못 박아도 LLM이 전문 속의 원래 있던 문장(예: "증명을
    요구하면 그 증명을 하여야 하고" — diff_parts엔 없는, 바뀌지 않은
    부분)까지 "추가된 내용"인 것처럼 요약에 섞어 넣었다. 맥락을 주는
    이득보다 이 오염 위험이 더 커서 되돌렸다 — 요약 대상은 diff_parts
    로만 한정하고, "또는"/"및" 같은 연결어를 놓치지 않는 것은 SYSTEM의
    규칙 7(연결어 보존)로 대신한다. diff_parts 자체엔 이미 그 연결어가
    포함돼 있으므로(예: "' 또는 자료의 제공' 추가"), 맥락 없이도 지킬
    수 있는 규칙이다.
    """
    lines = ["[바뀐 부분 — 이것만 문장으로 다듬으십시오]"]
    for part in unit.diff_parts:
        lines.append(f"  · {part}")
    return "\n".join(lines)


def build_article_prompt(unit: ArticleUnit) -> tuple[str, str]:
    """(system, user) 프롬프트를 만든다."""
    header = [f"법령명: {unit.law_name}", f"변경 유형: {unit.change_type}"]
    if unit.moved_from:
        header.append(f"(원래 {unit.moved_from} 에 있던 내용이 옮겨온 것 — 신설 아님)")

    body: list[str]
    if unit.change_type == "신설":
        body = ["[새로 생긴 내용]", unit.new_text or "(내용 없음)"]
    elif unit.change_type == "삭제":
        body = ["[삭제된 내용]", unit.old_text or "(내용 없음)"]
    elif unit.diff_parts:
        # 제자리 개정 / 이동후개정 — 바뀐 조각만 준다.
        body = [_diff_section(unit)]
        if unit.moved_from:
            body.insert(0, f"이 항목은 {unit.moved_from} 에서 옮겨오며 내용도 바뀌었습니다.")
    elif unit.is_whole_replace:
        # 항목이 통째로 교체됨. 개정 전/후를 나란히 주고 "무엇에서 무엇으로
        # 교체"로 서술하게 한다. (부분 조각으로 쪼개면 뒤죽박죽이 되므로 전문.)
        body = [
            "이 항목은 내용이 통째로 교체되었습니다. 개정 전 내용과 개정 후 내용을"
            " 각각 파악해, '무엇이 무엇으로 바뀌었다'는 식으로 서술하십시오."
            " 두 문장의 단어를 섞지 마십시오.",
            "[개정 전]",
            unit.old_text or "(없음)",
            "[개정 후]",
            unit.new_text or "(없음)",
        ]
    else:
        body = [
            "[개정 전]",
            unit.old_text or "(없음)",
            "[개정 후]",
            unit.new_text or "(없음)",
        ]

    tail = ["위 변경 내용을 한두 문장으로 요약하십시오."]
    return SYSTEM, "\n\n".join(["\n".join(header), *body, *tail])
